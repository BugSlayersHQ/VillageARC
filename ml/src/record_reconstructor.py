# MAIN
# ============================================================

def main():

    if not INPUT.exists():
        raise FileNotFoundError(
            f"Input file not found: {INPUT}"
        )

    with INPUT.open(
        "r",
        encoding="utf-8"
    ) as f:
        data = json.load(f)

    reconstructed = reconstruct_document(data)

    OUTPUT.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    with OUTPUT.open(
        "w",
        encoding="utf-8"
    ) as f:
        json.dump(
            reconstructed,
            f,
            ensure_ascii=False,
            indent=2
        )

    print()
    print("=" * 60)
    print("TABLE RECONSTRUCTION COMPLETE")
    print("=" * 60)
    print()

    print(
        f"Land records: "
        f"{len(reconstructed['land_records'])}"
    )

    print(
        f"Continuation rows: "
        f"{len(reconstructed['continuation'])}"
    )

    print()

    for record in reconstructed["land_records"]:

        print(
            f"ROW {record['row_number']}:"
        )

        print(
            "  serial:",
            record["serial_number"]
        )

        print(
            "  area:",
            record["plot_area"]
        )

        print(
            "  owner:",
            record["landowner_details"]
        )

        print(
            "  crop:",
            record["crop_name"]
        )

        print(
            "  crop area:",
            record["crop_area"]
        )

        print()

    print(
        f"Output: {OUTPUT}"
    )


if __name__ == "__main__":
    main()